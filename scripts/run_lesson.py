"""Replay the lesson against the compose database with the load running the whole time.

Baseline, the lock pile-up, the safe migration, the concurrent index, NOT NULL in three moves and the plan flip.
Numbers go to sql/explain/results.md, the lock queue to sql/explain/lock_queue.txt, plans to sql/explain/f*.txt.
Set BASELINE_SECONDS=600 for the lesson's ten-minute baseline.
"""
import os
import time

from app import db, migrate, scenarios
from app.load import LoadRunner

BASELINE_SECONDS = int(os.environ.get("BASELINE_SECONDS", "60"))


def say(text):
    print(text, flush=True)


def step(runner, label):
    say(label)
    runner.mark(label)


def table_size(connection):
    row = connection.execute(
        "SELECT pg_size_pretty(pg_table_size('events')), n_dead_tup FROM pg_stat_user_tables WHERE relname = 'events'").fetchone()
    return {"size": row[0], "dead": row[1]}


def main():
    results = {}
    with db.connect() as connection, LoadRunner(metrics_path="load-metrics.jsonl") as runner:
        step(runner, "== reset to the seed's rows")
        scenarios.reset_lab(connection)
        results["rows"] = connection.execute("SELECT count(*) FROM events").fetchone()[0]

        step(runner, f"== step 1: baseline, {BASELINE_SECONDS} s of steady load")
        results["baseline"] = baseline = runner.measure(BASELINE_SECONDS)
        say(f"   {baseline}")
        results["size_before"] = table_size(connection)

        step(runner, "== step 2: a long read, then a naive ALTER behind it")
        results["lock_queue"] = queue = scenarios.lock_queue(runner)
        say(queue["text"])
        say(f"   load during the pile-up: {queue['during']}")
        (db.EXPLAIN_DIR / "lock_queue.txt").write_text(queue["text"])
        scenarios.reset_lab(connection)

        step(runner, "== step 3: the safe migration")
        results["conflict"] = scenarios.forced_conflict()
        say(f"   forced conflict: {results['conflict']}")
        results["safe"] = safe = scenarios.safe_add_column_and_backfill(runner, connection)
        say(f"   {safe}")
        results["size_after_backfill"] = table_size(connection)

        step(runner, "== step 4: the index")
        results["plain_index"] = scenarios.plain_index_blocks_writes(runner, connection)
        say(f"   plain CREATE INDEX: {results['plain_index']}")
        results["concurrent"] = scenarios.concurrent_index(runner, connection)
        say(f"   CREATE INDEX CONCURRENTLY: {results['concurrent']}")

        step(runner, "== step 5: NOT NULL")
        results["naive_not_null"] = scenarios.naive_set_not_null(runner, connection)
        say(f"   naive: {results['naive_not_null']}")
        results["safe_not_null"] = scenarios.safe_not_null(runner, connection)
        say(f"   three moves: {results['safe_not_null']}")

        step(runner, "== step 6: the plan flip")
        flip = scenarios.plan_flip(connection)
        results["flip"] = {"actual_rows": flip["actual_rows"],
                           "plans": {name: scenarios.plan_numbers(lines) for name, lines in flip["plans"].items()}}
        say(f"   {results['flip']}")
        scenarios.reset_lab(connection)

        step(runner, "== closing baseline: the machine's own noise, to bracket the changes")
        results["closing_baseline"] = runner.measure(20)
        say(f"   {results['closing_baseline']}")
    write_results(results)
    say("== done: sql/explain/results.md")


def verdict(window, baseline):
    ok = window["p99_ms"] <= 2 * baseline["p99_ms"] and window["errors"] == 0 and window["stalled_seconds"] == 0
    return "yes" if ok else "no"


def row(label, window, baseline):
    return (f"| {label} | {window['ops_per_second']} | {window['errors']} | {window['p99_ms']} | {window['max_ms']} | "
            f"{window['worst_second_p99_ms']} | {window['stalled_seconds']} | {verdict(window, baseline)} |")


def write_results(results):
    opening = results["baseline"]
    # The bar is twice the higher of the opening and closing baselines: other work on the machine moves p99 too.
    baseline = max(opening, results["closing_baseline"], key=lambda window: window["p99_ms"])
    out = ["# Results of the last `make run`", "",
           f"Generated by `scripts/run_lesson.py` on {results['rows']:,} rows with the load running throughout "
           f"({BASELINE_SECONDS} s baseline). The load is 40 iterations a second of insert, update and read (120 operations a second).", "",
           "## What the load felt", "",
           "p99 is over the requests (one insert, one update and one read) that finished in the window; max is the slowest single statement. "
           "Worst second is the highest one-second p99 over single statements, which also "
           "counts operations still waiting, so a stall shows even when nothing completes. A stalled second is one in which "
           "an operation had waited 500 ms or more. The last column is the strict test: p99 at most twice the baseline, no errors and no stalled second. "
           "The lesson asks for it only of the safe migration (step 3); for the others read max ms and stalled seconds.", "",
           "| Window | Ops/s | Errors | p99 ms | Max ms | Worst second p99 ms | Stalled seconds | Within 2x, no errors, no stall |",
           "|---|---:|---:|---:|---:|---:|---:|---|",
           row("1 baseline, opening", opening, baseline),
           row("1 baseline, closing (20 s)", results["closing_baseline"], baseline),
           row(f"2 naive ALTER behind a long read ({results['lock_queue']['hold_seconds']} s)", results["lock_queue"]["during"], baseline),
           row(f"3 safe migration: add column, full backfill ({results['safe']['seconds']:.0f} s)", results["safe"]["summary"], baseline),
           row(f"4 plain CREATE INDEX ({results['plain_index']['build_seconds']:.1f} s build)", results["plain_index"]["summary"], baseline),
           row(f"4 CREATE INDEX CONCURRENTLY ({results['concurrent']['build_seconds']:.1f} s build)", results["concurrent"]["summary"], baseline),
           row(f"5 naive SET NOT NULL ({results['naive_not_null']['report']['seconds'] * 1000:.0f} ms)", results["naive_not_null"]["summary"], baseline),
           row("5 NOT NULL in three moves", results["safe_not_null"]["summary"], baseline), "",
           f"Baseline p99 for the bar: {baseline['p99_ms']} ms (the higher of the opening and closing baselines). After the pile-up, with the long read released: {results['lock_queue']['after']['p99_ms']} ms p99.", "",
           "## Step 2: the lock queue", "",
           f"The naive `ALTER TABLE events ADD COLUMN flagged boolean` waited {results['lock_queue']['alter_seconds']:.1f} s for a read-only "
           "transaction and never held its lock until that ended. The snapshot taken mid-pile-up is in `lock_queue.txt`.", "",
           "```text", results["lock_queue"]["text"].rstrip(), "```", "",
           "## Step 3: the safe migration", "",
           f"- Forced conflict: with a long read open, the safe `ALTER` (lock_timeout 1 s) failed after {results['conflict']['seconds']:.2f} s "
           f"(failed fast: {results['conflict']['failed_fast']}). It still held up the load for that second: a failed attempt queues too, "
           "so the timeout is also the longest stall a retry can cause.",
           f"- Add column: {results['safe']['add_column_attempts']} attempt(s). Backfill: {results['safe']['batches']} batches of {migrate.BACKFILL_BATCH:,} rows "
           f"with a {migrate.BACKFILL_PAUSE_SECONDS} s pause, {results['safe']['seconds']:.0f} s in all; rows still NULL afterwards: {results['safe']['rows_still_null']}.",
           f"- Bloat: table {results['size_before']['size']} before, {results['size_after_backfill']['size']} after the backfill "
           f"({results['size_after_backfill']['dead']:,} dead row versions): every updated row is a new version.", "",
           "## Step 4: the index", "",
           f"- Plain `CREATE INDEX`: built in {results['plain_index']['build_seconds']:.1f} s; the load's slowest operation took "
           f"{results['plain_index']['summary']['max_ms']} ms (baseline max is a few milliseconds), because inserts and updates waited for the build.",
           f"- `CREATE INDEX CONCURRENTLY` interrupted on purpose: cancelled = {results['concurrent']['interrupted']['cancelled']}, "
           f"invalid indexes found = {results['concurrent']['interrupted']['invalid']}. Dropped, rebuilt in {results['concurrent']['build_seconds']:.1f} s "
           f"with {results['concurrent']['summary']['errors']} load errors and a slowest operation of {results['concurrent']['summary']['max_ms']} ms; "
           f"valid after rebuild: {results['concurrent']['valid_after_rebuild']}.", "",
           "## Step 5: NOT NULL in three moves", "",
           "| Move | Statement | Lock held | Time ms |", "|---|---|---|---:|"]
    steps = results["safe_not_null"]["steps"]
    for name, statement in (("add_check_not_valid", "ADD CONSTRAINT ... CHECK (flagged IS NOT NULL) NOT VALID"),
                            ("validate", "VALIDATE CONSTRAINT"), ("set_not_null", "SET NOT NULL, then DROP CONSTRAINT")):
        out.append(f"| {name} | `{statement}` | {', '.join(steps[name]['lock_modes'])} | {steps[name]['seconds'] * 1000:.1f} |")
    naive = results["naive_not_null"]["report"]
    out += ["", f"The naive `SET NOT NULL` on a scratch column held {', '.join(naive['lock_modes'])} for {naive['seconds'] * 1000:.0f} ms "
            "(a full scan), against a few milliseconds for the last move above.", "",
            "## Step 6: the plan flip", "",
            f"The new month holds {results['flip']['actual_rows']:,} rows with `region = 'pacific' AND city = 'seattle'`. "
            "Plans are in `f1_*.txt`, `f2_*.txt` and `f3_*.txt`.", "",
            "| Moment | Planner estimate | Actual rows | Plan | Execution ms |", "|---|---:|---:|---|---:|"]
    labels = {"f1_stale_statistics": "Before statistics catch up", "f2_after_analyze": "After ANALYZE",
              "f3_after_extended_statistics": "After extended statistics"}
    for name, numbers in results["flip"]["plans"].items():
        out.append(f"| {labels[name]} | {numbers['estimate']:,} (filtered scan node) | {results['flip']['actual_rows']:,} | "
                   f"{numbers['nodes']} | {numbers['milliseconds']} |")
    (db.EXPLAIN_DIR / "results.md").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    started = time.time()
    main()
    say(f"finished in {time.time() - started:.0f} s")
